import io
import os
import unittest
from pathlib import Path
from uuid import uuid4

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import CheckConstraint, Connection, inspect, text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.schema import CreateSchema, DropSchema

from FOIHireloom.db.models import Base


class AlembicMigrationTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self) -> None:
        database_url = os.environ.get("TEST_DATABASE_URL")
        if not database_url:
            self.skipTest("Set TEST_DATABASE_URL to run PostgreSQL migration tests")
        if not database_url.startswith("postgresql+asyncpg://"):
            raise ValueError("TEST_DATABASE_URL must use postgresql+asyncpg")

        self.schema = f"test_migrations_{uuid4().hex}"
        self.admin_engine = create_async_engine(database_url)
        self.addAsyncCleanup(self.admin_engine.dispose)
        async with self.admin_engine.begin() as connection:
            await connection.execute(CreateSchema(self.schema))
        self.addAsyncCleanup(self.drop_schema)

        self.engine = create_async_engine(
            database_url,
            connect_args={"server_settings": {"search_path": self.schema}},
        )
        self.addAsyncCleanup(self.engine.dispose)
        config_path = (
            Path(__file__).resolve().parents[1]
            / "src/FOIHireloom/db/alembic/alembic.ini"
        )
        self.config = Config(str(config_path), stdout=io.StringIO())

    async def drop_schema(self) -> None:
        async with self.admin_engine.begin() as connection:
            await connection.execute(DropSchema(self.schema, cascade=True))

    def execute_command(self, connection: Connection, operation, *args) -> None:
        self.config.attributes["connection"] = connection
        try:
            operation(self.config, *args)
        finally:
            self.config.attributes.pop("connection", None)

    async def migrate(self, operation, *args) -> None:
        async with self.engine.begin() as connection:
            await connection.run_sync(self.execute_command, operation, *args)

    async def table_names(self) -> set[str]:
        async with self.engine.connect() as connection:
            return await connection.run_sync(lambda conn: set(inspect(conn).get_table_names()))

    async def current_revision(self) -> str | None:
        async with self.engine.connect() as connection:
            return await connection.run_sync(
                lambda conn: MigrationContext.configure(conn).get_current_revision()
            )

    def verify_constraints(self, connection: Connection) -> None:
        inspector = inspect(connection)
        for table in Base.metadata.tables.values():
            actual_checks = {check["name"] for check in inspector.get_check_constraints(table.name)}
            expected_checks = {
                constraint.name for constraint in table.constraints
                if isinstance(constraint, CheckConstraint)
            }
            self.assertEqual(actual_checks, expected_checks, table.name)
            self.assertEqual(
                set(inspector.get_pk_constraint(table.name)["constrained_columns"]),
                {column.name for column in table.primary_key},
                table.name,
            )
            actual_foreign_keys = {
                (tuple(key["constrained_columns"]), key["referred_table"], key["options"].get("ondelete"))
                for key in inspector.get_foreign_keys(table.name)
            }
            expected_foreign_keys = {
                ((key.parent.name,), key.column.table.name, key.ondelete)
                for key in table.foreign_keys
            }
            self.assertEqual(actual_foreign_keys, expected_foreign_keys, table.name)

    async def test_upgrade_matches_models_and_preserves_all_named_constraints(self) -> None:
        await self.migrate(command.upgrade, "head")
        self.assertEqual(await self.table_names(), set(Base.metadata.tables) | {"alembic_version"})
        head = ScriptDirectory.from_config(self.config).get_current_head()
        self.assertEqual(await self.current_revision(), head)
        await self.migrate(command.check)
        async with self.engine.connect() as connection:
            await connection.run_sync(self.verify_constraints)
            index_definition = await connection.scalar(text(
                "SELECT indexdef FROM pg_indexes WHERE schemaname = :schema "
                "AND indexname = 'ix_sync_runs_feed_id_started_at'"
            ), {"schema": self.schema})
            self.assertIn("started_at DESC", index_definition)

    async def test_upgrade_is_idempotent_and_downgrade_allows_clean_reupgrade(self) -> None:
        await self.migrate(command.upgrade, "head")
        async with self.engine.begin() as connection:
            await connection.execute(text("INSERT INTO counties (code, name) VALUES ('zagreb', 'Grad Zagreb')"))
        await self.migrate(command.upgrade, "head")
        async with self.engine.connect() as connection:
            self.assertEqual(await connection.scalar(text("SELECT count(*) FROM counties")), 1)
        await self.migrate(command.downgrade, "base")
        self.assertEqual(await self.table_names(), {"alembic_version"})
        self.assertIsNone(await self.current_revision())
        await self.migrate(command.upgrade, "head")
        await self.migrate(command.check)

    async def test_check_detects_schema_drift(self) -> None:
        await self.migrate(command.upgrade, "head")
        async with self.engine.begin() as connection:
            await connection.execute(text("ALTER TABLE jobs ADD COLUMN unexpected_column INTEGER"))
        with self.assertRaises(AutogenerateDiffsDetected):
            await self.migrate(command.check)

    async def test_search_migration_backfills_municipality_and_downgrade_restores_dropped_columns(self) -> None:
        await self.migrate(command.upgrade, "1981498b73b5")
        description = ("Opis posla: KUHAR, Kategorija: UGOSTITELJI, RADNICI U TURIZMU, Rok za prijavu: 30.10.2026, "
                       "Mjesto rada: VELIKA BARNA, Općina: GRUBIŠNO POLJE, Županija: BJELOVARSKO-BILOGORSKA")
        async with self.engine.begin() as connection:
            feed_id = await connection.scalar(text(
                "INSERT INTO source_feeds (ckan_resource_id, label, feed_url, scope) "
                "VALUES (gen_random_uuid(), 'EU', 'https://example.com/eu.xml', 'eu') RETURNING id"
            ))
            job_id = await connection.scalar(text(
                "INSERT INTO jobs (provider, source_job_id, source_guid, canonical_url, title, subject, "
                "description_raw, description_text, content_hash) VALUES ('hzz', '1', "
                "'http://burzarada.hzz.hr/RadnoMjesto_Ispis.aspx?WebSifra=1', "
                "'https://burzarada.hzz.hr/RadnoMjesto_Ispis.aspx?WebSifra=1', 'KUHAR', 'KUHAR', "
                ":description, 'Kuhanje jela', 'hash') RETURNING id"
            ), {"description": description})
            await connection.execute(text(
                "INSERT INTO job_feed_memberships (job_id, feed_id, source_item) VALUES (:job, :feed, '{\"a\": 1}')"
            ), {"job": job_id, "feed": feed_id})

        await self.migrate(command.upgrade, "head")
        async with self.engine.connect() as connection:
            row = (await connection.execute(text(
                "SELECT municipality, search_vector @@ plainto_tsquery('simple', 'kuhanje') FROM jobs"
            ))).one()
            self.assertEqual(tuple(row), ("GRUBIŠNO POLJE", True))
            columns = await connection.run_sync(lambda conn: {
                table: {column["name"] for column in inspect(conn).get_columns(table)}
                for table in ("jobs", "job_feed_memberships")
            })
        self.assertTrue({"subject", "source_guid"}.isdisjoint(columns["jobs"]))
        self.assertNotIn("source_item", columns["job_feed_memberships"])

        await self.migrate(command.downgrade, "1981498b73b5")
        async with self.engine.connect() as connection:
            restored = (await connection.execute(text(
                "SELECT j.subject, j.source_guid, m.source_item FROM jobs j JOIN job_feed_memberships m ON m.job_id = j.id"
            ))).one()
        self.assertEqual(tuple(restored), ("KUHAR", "http://burzarada.hzz.hr/RadnoMjesto_Ispis.aspx?WebSifra=1", {}))
        await self.migrate(command.upgrade, "head")
        await self.migrate(command.check)

    async def test_page_search_migration_rebuilds_the_search_vector_both_ways(self) -> None:
        await self.migrate(command.upgrade, "adc0c83dfede")
        async with self.engine.begin() as connection:
            await connection.execute(text(
                "INSERT INTO jobs (provider, source_job_id, canonical_url, title, description_text, content_hash, "
                "page_status, page_checked_at, page_fetched_at, page_source_hash, page_title, page_description_text) "
                "VALUES ('hzz', '1', 'https://example.com/1', 'KUHAR', 'Kuhanje jela', 'hash', 'fetched', now(), "
                "now(), 'hash', 'KUHAR/KUHARICA', 'Potreban njemački jezik.')"
            ))

        async def matches(*queries: str) -> tuple[bool, ...]:
            async with self.engine.connect() as connection:
                return tuple([
                    await connection.scalar(text("SELECT search_vector @@ to_tsquery('simple', :query) FROM jobs"),
                                            {"query": query})
                    for query in queries
                ])

        self.assertEqual(await matches("njemacki", "kuhanje", "kuharica:*A"), (False, True, False))
        await self.migrate(command.upgrade, "head")
        self.assertEqual(await matches("njemacki", "kuhanje", "kuharica:*A", "njemacki:*A"), (True, False, True, False))
        await self.migrate(command.downgrade, "adc0c83dfede")
        self.assertEqual(await matches("njemacki", "kuhanje"), (False, True))
        await self.migrate(command.upgrade, "head")
        await self.migrate(command.check)

    async def test_occupation_feed_migration_allows_feeds_without_county_and_downgrade_removes_them(self) -> None:
        await self.migrate(command.upgrade, "head")
        insert_feed = text(
            "INSERT INTO source_feeds (county_id, ckan_resource_id, label, feed_url, scope) "
            "VALUES (:county, gen_random_uuid(), 'Zanimanje', :url, :scope) RETURNING id"
        )
        async with self.engine.begin() as connection:
            county_id = await connection.scalar(text(
                "INSERT INTO counties (code, name) VALUES ('zagreb', 'Grad Zagreb') RETURNING id"
            ))
            county_feed = await connection.scalar(
                insert_feed, {"county": county_id, "url": "https://example.com/zup.xml", "scope": "county"}
            )
            occupation_feed = await connection.scalar(
                insert_feed, {"county": None, "url": "https://example.com/kat.xml", "scope": "occupation"}
            )
            job_id = await connection.scalar(text(
                "INSERT INTO jobs (provider, source_job_id, canonical_url, content_hash) "
                "VALUES ('hzz', '1', 'https://example.com/1', 'hash') RETURNING id"
            ))
            for feed_id in (county_feed, occupation_feed):
                await connection.execute(text(
                    "INSERT INTO job_feed_memberships (job_id, feed_id) VALUES (:job, :feed)"
                ), {"job": job_id, "feed": feed_id})
                await connection.execute(text("INSERT INTO sync_runs (feed_id) VALUES (:feed)"), {"feed": feed_id})
        with self.assertRaises(IntegrityError):
            async with self.engine.begin() as connection:
                await connection.execute(
                    insert_feed, {"county": county_id, "url": "https://example.com/bad.xml", "scope": "occupation"}
                )

        await self.migrate(command.downgrade, "9acbc4dd1c66")
        async with self.engine.connect() as connection:
            remaining = (await connection.execute(text(
                "SELECT (SELECT array_agg(scope) FROM source_feeds), "
                "(SELECT count(*) FROM job_feed_memberships), (SELECT count(*) FROM sync_runs)"
            ))).one()
        self.assertEqual(tuple(remaining), (["county"], 1, 1))
        await self.migrate(command.upgrade, "head")
        await self.migrate(command.check)

    async def test_category_mapping_migration_keeps_feeds_and_rejects_county_mappings(self) -> None:
        await self.migrate(command.upgrade, "head")
        insert_feed = text(
            "INSERT INTO source_feeds (county_id, ckan_resource_id, label, feed_url, scope, mapped_category, "
            "mapping_status, mapping_matching_examples, mapping_contradicting_examples, mapping_verified_at) "
            "VALUES (:county, gen_random_uuid(), 'Zanimanje', :url, :scope, 'STRUČNJACI U PROMETU', "
            "'confirmed', 383, 0, now())"
        )
        async with self.engine.begin() as connection:
            county_id = await connection.scalar(text(
                "INSERT INTO counties (code, name) VALUES ('zagreb', 'Grad Zagreb') RETURNING id"
            ))
            await connection.execute(insert_feed, {"county": None, "url": "https://example.com/kat.xml", "scope": "occupation"})
        with self.assertRaises(IntegrityError):
            async with self.engine.begin() as connection:
                await connection.execute(
                    insert_feed, {"county": county_id, "url": "https://example.com/zup.xml", "scope": "county"}
                )

        await self.migrate(command.downgrade, "4668a0c36bbc")
        async with self.engine.connect() as connection:
            columns = await connection.scalar(text(
                "SELECT count(*) FROM information_schema.columns "
                "WHERE table_name = 'source_feeds' AND column_name LIKE 'mapp%'"
            ))
            feeds = await connection.scalar(text("SELECT count(*) FROM source_feeds"))
        self.assertEqual((columns, feeds), (0, 1))
        await self.migrate(command.upgrade, "head")
        await self.migrate(command.check)

    async def test_category_source_migration_marks_parsed_categories_and_downgrade_drops_filled_ones(self) -> None:
        await self.migrate(command.upgrade, "b7d2e5a1c3f9")
        insert_job = text(
            "INSERT INTO jobs (provider, source_job_id, canonical_url, content_hash, category) "
            "VALUES ('hzz', :id, 'https://example.com/' || :id, 'hash', :category)"
        )
        async with self.engine.begin() as connection:
            for job_id, category in (("1", "STRUČNJACI U PROMETU"), ("2", None), ("3", None)):
                await connection.execute(insert_job, {"id": job_id, "category": category})
        await self.migrate(command.upgrade, "head")
        sources = text("SELECT source_job_id, category, category_source FROM jobs ORDER BY source_job_id")
        async with self.engine.begin() as connection:
            rows = (await connection.execute(sources)).all()
            self.assertEqual([tuple(row) for row in rows], [
                ("1", "STRUČNJACI U PROMETU", "description"), ("2", None, None), ("3", None, None),
            ])
            feed_id = await connection.scalar(text(
                "INSERT INTO source_feeds (ckan_resource_id, label, feed_url, scope) "
                "VALUES (gen_random_uuid(), 'Zanimanje', 'https://example.com/kat.xml', 'occupation') RETURNING id"
            ))
            await connection.execute(text(
                "UPDATE jobs SET category = 'TEKSTILCI I KOŽARI', category_source = 'feed', category_feed_id = :feed "
                "WHERE source_job_id = '3'"
            ), {"feed": feed_id})

        await self.migrate(command.downgrade, "b7d2e5a1c3f9")
        async with self.engine.connect() as connection:
            categories = (await connection.execute(text(
                "SELECT source_job_id, category FROM jobs ORDER BY source_job_id"
            ))).all()
        self.assertEqual([tuple(row) for row in categories], [("1", "STRUČNJACI U PROMETU"), ("2", None), ("3", None)])
        await self.migrate(command.upgrade, "head")
        await self.migrate(command.check)
